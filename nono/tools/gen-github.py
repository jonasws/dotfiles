#!/usr/bin/env python3
"""Generate nono/profiles/liflig-github.json from nono/github-repos.txt.

Agents read the listed private repositories through gh, and nothing else of
yours. Two layers, both of which must allow a call:

- Command policy: only the gh command gets the private-capable token
  (keychain item nono/github_pat). Everything else in the sandbox, the GitHub
  MCP server included, keeps the public-read token of the base profile. gh runs only
  fixed read subcommands, whose GraphQL gh writes itself; `gh api` is out,
  since its flags can turn any call into a GraphQL mutation. -R and --repo
  are refused and GH_REPO is not passed on, so gh takes the repository from
  the working directory.
- Endpoint policy on that token: GET and HEAD under /repos/<owner>/<name>
  for each listed repository, plus the few account-level reads gh makes.
  gh's pr, issue and repo commands speak GraphQL, whose body nono cannot
  read, so gh gets POST /graphql and leans on the command policy above.

Run after editing the list:  python3 -I nono/tools/gen-github.py
"""

import json
import pathlib

ROOT = pathlib.Path(__file__).resolve().parents[2]
REPOS = ROOT / "nono" / "github-repos.txt"
OUT = ROOT / "nono" / "profiles" / "liflig-github.json"

ACCOUNT_READS = ["/user", "/rate_limit", "/meta"]

# gh gets these variables and no others, so GH_REPO and GH_HOST never reach it.
# Proxy settings and the phantom token are added by nono after this filter.
GH_ENV = [
    "HOME", "USER", "LOGNAME", "TERM", "COLORTERM", "LANG", "LC_*", "TZ", "TMPDIR",
    "NO_COLOR", "CLICOLOR*", "PAGER", "GH_PAGER", "GH_FORCE_TTY", "GH_PROMPT_DISABLED",
    "GH_NO_UPDATE_NOTIFIER", "GH_SPINNER_DISABLED", "SSL_CERT_FILE", "SSL_CERT_DIR",
    "GIT_*", "XDG_*", "MISE_*",
]

READ_SUBCOMMANDS = [
    ["pr", "list"], ["pr", "view"], ["pr", "diff"], ["pr", "checks"], ["pr", "status"],
    ["issue", "list"], ["issue", "view"], ["issue", "status"],
    ["run", "list"], ["run", "view"], ["workflow", "list"], ["workflow", "view"],
    ["release", "list"], ["release", "view"],
    ["repo", "view"],
    ["auth", "status"],
    ["--version"], ["help"],
]


def repos():
    out = []
    for line in REPOS.read_text().splitlines():
        line = line.strip()
        if not line or line.startswith("#"):
            continue
        owner, _, name = line.partition("/")
        if not owner or not name or "/" in name or "*" in line:
            raise SystemExit(f"gen-github: not owner/name: {line!r}")
        out.append(line)
    return out


def repo_rules(names):
    rules = []
    for full in names:
        for method in ("GET", "HEAD"):
            rules.append({"method": method, "path": f"/repos/{full}"})
            rules.append({"method": method, "path": f"/repos/{full}/**"})
    for path in ACCOUNT_READS:
        rules.append({"method": "GET", "path": path})
    return rules


def credential(env_var):
    return {
        "type": "proxy",
        "upstream": "https://api.github.com",
        "credential_key": "github_pat",
        "env_var": env_var,
        "inject_header": "Authorization",
        "credential_format": "token {}",
    }


def main():
    names = repos()
    reads = repo_rules(names)
    profile = {
        "$schema": "https://raw.githubusercontent.com/nolabs-ai/nono/refs/heads/main/crates/nono-cli/data/nono-profile.schema.json",
        "meta": {
            "name": "liflig-github",
            "description": "Generated by nono/tools/gen-github.py from nono/github-repos.txt: gh reads the listed private repositories, read-only.",
        },
        "command_policies": {
            "credentials": {
                "github-private-gh": credential("GH_TOKEN"),
            },
            "commands": {
                "gh": {
                    "from": {
                        "session": {
                            "sandbox": {
                                "environment": {"allow_vars": GH_ENV},
                                "credentials": [{
                                    "name": "github-private-gh",
                                    "endpoint_policy": {
                                        "default": {"decision": "deny"},
                                        "allow": reads + [{"method": "POST", "path": "/graphql"}],
                                    },
                                }],
                            },
                            "invocation_policy": {
                                "default": {"decision": "deny"},
                                "deny": [
                                    {"argv": {"contains": ["-R"]}, "reason": "gh resolves the repository from the working directory"},
                                    {"argv": {"contains": ["--repo"]}, "reason": "gh resolves the repository from the working directory"},
                                ],
                                "allow": [{"argv": {"prefix": p}} for p in READ_SUBCOMMANDS],
                            },
                        },
                    },
                },
            },
        },
    }
    OUT.write_text(json.dumps(profile, indent=2) + "\n")
    print(f"{len(names)} repositories -> {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
