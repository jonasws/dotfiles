#!/usr/bin/env python3
"""Regenerate rgrc conf overrides that paint ANSI backgrounds, in Catppuccin Mocha.

rgrc emits plain 16-colour SGR codes, so `on_blue white` lands on the terminal's
pastel ANSI blue as light-on-light. Following the Catppuccin style guide
(coloured background + Crust text), every `on_<colour>` element is rewritten to
`rgb:<crust> on_rgb:<palette colour>`. Palette values come from whiskers.

On a blue background, a green or red foreground carries meaning (curl's HTTP
status lines), so that hue moves to the background instead of being dropped.

curl is also patched: upstream status regexps need a reason phrase, which HTTP/2
and HTTP/3 never send, and headers are only coloured behind a `<` (curl -v), so
`curl -i`/`-I` output stays plain.

Usage: generate-catppuccin.py [path/to/rgrc/share]
"""
import re
import subprocess
import sys
import tempfile
from pathlib import Path

HERE = Path(__file__).resolve().parent
FLAVOR = "mocha"
WHISKERS = ["mise", "x", "cargo:catppuccin-whiskers@2.5.1", "--", "whiskers"]

CONFS = [
    "curl",
    "dockerimages",
    "dockernetwork",
    "dockerps",
    "du",
    "fdisk",
    "lsof",
    "ps",
]

PATCHES = {
    "curl": (
        [(r"\d{2} [\w\s]+", r"\d{2}[\w\s]*")],
        "===\n# Headers without a direction prefix (curl -i / -I)\n"
        "regexp=^([\\w\\-]+): (.*)\ncolours=default, bright_blue, bright_cyan\n",
    ),
}

BACKGROUNDS = {
    "red": "red",
    "green": "green",
    "yellow": "yellow",
    "blue": "blue",
    "magenta": "pink",
    "cyan": "teal",
    "white": "subtext1",
    "black": "surface1",
}

SEMANTIC = {"green": "green", "bright_green": "green", "red": "red", "bright_red": "red"}

FOREGROUND = re.compile(
    r"^(black|red|green|yellow|blue|magenta|cyan|white|bright_\w+|colou?r_\d+|rgb:\w+)$"
)

TEMPLATE = """---
whiskers:
  version: ^2.5.1
  filename: null
---
{% for name, c in flavor.colors %}{{ name }}={{ c.hex }}
{% endfor %}"""


def palette():
    with tempfile.NamedTemporaryFile("w", suffix=".tera") as f:
        f.write(TEMPLATE)
        f.flush()
        out = subprocess.run(
            [*WHISKERS, f.name, "--flavor", FLAVOR],
            check=True, capture_output=True, text=True, cwd=HERE,
        ).stdout
    return dict(line.split("=") for line in out.split())


def default_share():
    candidates = sorted(
        Path.home().glob(".cargo/registry/src/*/rgrc-*/share"),
        key=lambda p: [int(x) for x in re.findall(r"\d+", p.parent.name)],
    )
    if not candidates:
        sys.exit("no rgrc source found under ~/.cargo/registry; pass the share dir")
    return candidates[-1]


def rewrite_element(element, colors):
    words = element.split()
    bg = next((w for w in words if w.startswith("on_") and w[3:] in BACKGROUNDS), None)
    if bg is None:
        return element
    name = bg[3:]
    if name == "blue":
        name = next((SEMANTIC[w] for w in words if w in SEMANTIC), name)
    fg = colors["text"] if name == "black" else colors["crust"]
    kept = [w for w in words if w != bg and not FOREGROUND.match(w)]
    return " ".join([*kept, f"rgb:{fg}", f"on_rgb:{colors[BACKGROUNDS[name]]}"])


def rewrite(text, colors):
    out, changed = [], 0
    for line in text.splitlines():
        m = re.match(r"^(colou?rs?=)(.*)$", line)
        if m:
            elements = [e.strip() for e in m.group(2).split(",")]
            new = [rewrite_element(e, colors) for e in elements]
            if new != elements:
                changed += 1
                line = m.group(1) + ",".join(new)
        out.append(line)
    return "\n".join(out) + "\n", changed


def main():
    share = Path(sys.argv[1]) if len(sys.argv) > 1 else default_share()
    colors = palette()
    origin = share.parent.name
    for name in CONFS:
        src = share / f"conf.{name}"
        source = src.read_text()
        replacements, extra = PATCHES.get(name, ([], ""))
        for old, new in replacements:
            source = source.replace(old, new)
        text, changed = rewrite(source.rstrip("\n") + "\n" + extra, colors)
        header = f"# Generated by generate-catppuccin.py from {origin} ({FLAVOR}); edit the script, not this file.\n"
        (HERE / f"conf.{name}").write_text(header + text)
        print(f"conf.{name}: {changed} rule(s) rewritten")


if __name__ == "__main__":
    main()
